const I18N_KEY = 'vm_lang';
/* localStorage directly rather than through `store`, which lives in js/game.js
   and is evaluated long after this file — and the language has to be known
   before the first paint, not after. Same try/catch, same reasons: private mode
   and blocked site data both throw on access rather than returning null. */
const langStore = {
  get() { try { return localStorage.getItem(I18N_KEY); } catch (e) { return null; } },
  set(v) { try { localStorage.setItem(I18N_KEY, v); } catch (e) {} }
};

const langHas = c => Object.prototype.hasOwnProperty.call(STR, c);

/* WHICH LANGUAGE, AND WHY THAT ONE.

   A stored choice wins outright — somebody who has picked a language has said
   what they want and a trip abroad must not change it. Otherwise the browser's
   own preference list is walked IN ORDER, because that list is already sorted by
   what its owner prefers: a phone reporting ['sr','en-GB'] wants Serbian even
   though English is also on it, and reading the list as a set would get that
   backwards. Each tag is tried whole and then cut at the dash, so en-GB, pt-BR
   and zh-Hans-CN all land somewhere useful. */
function langPick() {
  const saved = langStore.get();
  if (saved && langHas(saved)) return saved;
  const nav = (typeof navigator !== 'undefined' && navigator) || {};
  const list = nav.languages && nav.languages.length ? nav.languages
             : (nav.language ? [nav.language] : []);
  for (const raw of list) {
    const tag = String(raw || '').toLowerCase();
    if (langHas(tag)) return tag;
    const base = tag.split('-')[0];
    if (langHas(base)) return base;
  }
  return 'en';
}

let LANG = langPick();

/* One string. Missing keys fall back to English, then to the key itself — a key
   on screen is ugly but it is also unmistakable, which is what you want from the
   case that is not supposed to happen.

   AND IT IS CALLED txt RATHER THAN t, which is the conventional name and was the
   first one used here. `t` is bound as a local or a parameter in ninety-six
   places in this codebase — a timestamp in the loop, a traffic car, a building's
   tags, an interpolation factor, the ground attitude under a landing car — and
   every one of them shadows a global of the same name inside its own function.
   It cost one real crash: landCar in js/body3d.js does
   `const t = groundAttitude(...)` eleven lines above a toast, so a car finishing
   a jump on its roof called the attitude object as a function and took the whole
   frame down with it. Nothing warned; the file parses, and the shadow only bites
   on the path that lands upside down. A name that is free everywhere is worth
   more than a name that is short. */
function txt(key, vars) {
  const table = STR[LANG] || STR.en;
  let s = table[key];
  if (s == null) s = STR.en[key];
  if (s == null) return key;
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, name) =>
    (vars[name] == null ? m : String(vars[name])));
}

/* THE MARKUP, TRANSLATED IN PLACE.

   data-i18n sets text, data-i18n-html sets markup (the two hint lines and the
   credit carry <b> and <kbd> and a link), and the three attribute forms cover
   the things a screen reader and a tooltip read. Everything is looked up fresh
   on every call, so switching language re-runs exactly this and nothing has to
   remember what it used to say. */
function i18nApply(root) {
  const r = root || document;
  for (const el of r.querySelectorAll('[data-i18n]'))
    el.textContent = txt(el.getAttribute('data-i18n'));
  for (const el of r.querySelectorAll('[data-i18n-html]'))
    el.innerHTML = txt(el.getAttribute('data-i18n-html'), { osm: el.dataset.osm || '' });
  for (const el of r.querySelectorAll('[data-i18n-aria]'))
    el.setAttribute('aria-label', txt(el.getAttribute('data-i18n-aria')));
  for (const el of r.querySelectorAll('[data-i18n-title]'))
    el.setAttribute('title', txt(el.getAttribute('data-i18n-title')));
  for (const el of r.querySelectorAll('[data-i18n-ph]'))
    el.setAttribute('placeholder', txt(el.getAttribute('data-i18n-ph')));
  if (r === document || r === document.documentElement)
    document.documentElement.setAttribute('lang', LANG);
}

/* Switching language re-translates the markup and then asks the live parts of
   the game to say themselves again — the dial, the objective line, the mode
   button. Each is guarded: this file is loaded first and the others may not
   exist yet when a language is picked on the title screen. */
function setLang(code) {
  if (!langHas(code)) return false;
  LANG = code;
  langStore.set(code);
  i18nApply(document);
  if (typeof radioPaint === 'function') radioPaint();
  if (typeof syncGhostUI === 'function') syncGhostUI();
  if (typeof i18nRepaint === 'function') i18nRepaint();
  return true;
}
